present_tables AS (
  SELECT table_name FROM information_schema.tables
  WHERE table_schema='public' AND table_type='BASE TABLE'
)
-- (1) TABLES declared in schema.ts but absent from the database
SELECT '1-MISSING TABLE' AS kind, d.t AS table_name, NULL::text AS column_name
FROM (SELECT DISTINCT t FROM declared) d
WHERE d.t NOT IN (SELECT table_name FROM present_tables)
UNION ALL
-- (2) COLUMNS missing, on tables that DO exist
SELECT '2-MISSING COLUMN', d.t, d.c
FROM declared d
JOIN present_tables p ON p.table_name = d.t
LEFT JOIN information_schema.columns i
  ON i.table_schema='public' AND i.table_name=d.t AND i.column_name=d.c
WHERE i.column_name IS NULL
UNION ALL
-- (3) COLUMNS in the database that schema.ts does not declare (reverse drift)
SELECT '3-EXTRA COLUMN', i.table_name, i.column_name
FROM information_schema.columns i
JOIN present_tables p ON p.table_name = i.table_name
WHERE i.table_schema='public'
  AND i.table_name IN (SELECT DISTINCT t FROM declared)
  AND NOT EXISTS (SELECT 1 FROM declared d WHERE d.t=i.table_name AND d.c=i.column_name)
ORDER BY 1,2,3;
